const parts = (text) => text.split('|').map((value) => value.trim());
function incident(number, category, title, service, symptoms, logs, cause, evidence, diagnosis, resolution, verification, prevention) {
  return {
    incidentId: `HIST-${String(number).padStart(3, '0')}`,
    title, category, affectedService: service,
    symptoms: parts(symptoms), exampleLogPatterns: parts(logs), rootCause: cause,
    supportingEvidence: parts(evidence).map((item) => `Synthetic evidence: ${item}`),
    troubleshootingSteps: parts(diagnosis),
    recommendedResolution: ['Obtain authorised human review before operational changes.', ...parts(resolution)],
    verificationChecks: parts(verification), preventiveActions: parts(prevention),
    sourceType: 'synthetic', seedDataset: SEED_DATASET,
    tags: [category.toLowerCase(), service, 'synthetic'], runbookReferences: [],
  };
}

